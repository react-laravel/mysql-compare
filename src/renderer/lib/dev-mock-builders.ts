export function terminalCommandOutput(command: string): string {
  switch (command) {
    case '':
      return ''
    case 'ls':
      return 'app  current  deploy.sh  notes.md  releases  shop-2026-07-26.sql.gz'
    case 'pwd':
      return '/home/deploy'
    case 'whoami':
      return 'deploy'
    case 'uname -a':
      return 'Linux bastion 6.8.0-45-generic #45-Ubuntu SMP x86_64 GNU/Linux'
    default:
      return `${command.split(' ')[0] ?? command}: command not found`
  }
}


export function executeStatements(sql: string): unknown {
  const statements = sql
    .split(';')
    .map((part) => part.trim())
    .filter((part) => part.length > 0)

  if (statements.length === 0) return []

  const run = (statement: string): unknown => {
    const head = statement.slice(0, 12).toLowerCase()
    if (head.startsWith('select') || head.startsWith('show') || head.startsWith('with') || head.startsWith('describe') || head.startsWith('desc ')) {
      const table = /\bfrom\s+[`"']?([a-z_][a-z0-9_]*)/i.exec(statement)?.[1] ?? 'users'
      const def = tableDef(table)
      const limit = Number(/\blimit\s+(\d+)/i.exec(statement)?.[1] ?? 25)
      return Array.from({ length: Math.min(limit, 100, def.rowCount) }, (_, i) => def.makeRow(i))
    }
    return { affectedRows: (statement.length % 9) + 1, insertId: 0, warningStatus: 0 }
  }

  if (statements.length === 1) {
    const only = statements[0]
    return only === undefined ? [] : run(only)
  }
  return statements.map((statement) => {
    const result = run(statement)
    return Array.isArray(result) ? { affectedRows: result.length, insertId: 0 } : result
  })
}

export function explainResult(engine: SqlDbEngine, sql: string): ExplainSQLResult {
  const table = /\bfrom\s+[`"']?([a-z_][a-z0-9_]*)/i.exec(sql)?.[1] ?? 'users'
  const def = tableDef(table)
  const rows = def.primaryKey.length > 0 ? Math.ceil(def.rowCount / 4) : def.rowCount
  return {
    engine,
    statement: sql,
    summary: [
      { label: 'Estimated rows', value: rows },
      { label: 'Estimated cost', value: (rows * 1.12).toFixed(2) },
      { label: 'Access type', value: def.primaryKey.length > 0 ? 'range' : 'ALL' }
    ],
    plan: {
      id: 'node-0',
      label: engine === 'postgres' ? 'Seq Scan' : 'SIMPLE',
      detail: table,
      metrics: [
        { label: 'rows', value: rows },
        { label: 'filtered', value: '62.50%' }
      ],
      children:
        def.indexes.length > 1
          ? [
              {
                id: 'node-1',
                label: engine === 'postgres' ? 'Index Scan' : 'ref',
                detail: def.indexes[1]?.name ?? 'PRIMARY',
                metrics: [{ label: 'rows', value: Math.ceil(rows / 8) }],
                children: []
              }
            ]
          : []
    },
    columns: ['id', 'select_type', 'table', 'type', 'rows', 'Extra'],
    rows: [
      {
        id: 1,
        select_type: 'SIMPLE',
        table,
        type: def.primaryKey.length > 0 ? 'range' : 'ALL',
        rows,
        Extra: 'Using where'
      }
    ]
  }
}
