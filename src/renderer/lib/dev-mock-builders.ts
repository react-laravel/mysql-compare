export function buildSyncPlan(tables: string[], syncStructure: boolean, syncData: boolean): SyncPlan {
  return {
    steps: tables.map((table) => {
      const def = tableDef(table)
      const sqls: string[] = []
      if (syncStructure) {
        sqls.push(`DROP TABLE IF EXISTS \`${table}\`;`)
        sqls.push(renderCreateSQL('mysql', table, def))
      }
      if (syncData) {
        const columns = def.columns.map((c) => `\`${c.name}\``).join(', ')
        sqls.push(`INSERT INTO \`${table}\` (${columns}) VALUES /* ${def.rowCount} rows */ ...;`)
      }
      return {
        table,
        description:
          syncStructure && syncData
            ? `Recreate ${table} and copy ${def.rowCount} rows`
            : syncStructure
              ? `Recreate ${table}`
              : `Copy ${def.rowCount} rows into ${table}`,
        sqls
      }
    })
  }
}


